#!/usr/bin/env node
/**
 * Renders public/map-arad.svg: real OpenStreetMap geometry (roads, buildings,
 * parks, water) around Str. Bagdazar, Arad, drawn in the site's illustrated
 * map style (cream ground, sand blocks, white roads with tan casing, sage
 * parks). Run once and commit the output:  node scripts/render-map.mjs
 *
 * Data © OpenStreetMap contributors (ODbL).
 */
import { writeFile } from 'node:fs/promises';

// Map centre (Str. Bagdazar, neighbourhood level) and extent in metres.
const CENTER = { lat: 46.1398, lon: 21.3150 };
const WIDTH_M = 1600;
const HEIGHT_M = 1200; // 4:3
const W = 1200; // SVG units
const H = 900;

const mPerDegLat = 111_132;
const mPerDegLon = 111_320 * Math.cos((CENTER.lat * Math.PI) / 180);
const dLat = HEIGHT_M / 2 / mPerDegLat;
const dLon = WIDTH_M / 2 / mPerDegLon;
// fetch a margin so features crossing the edge are complete
const pad = 1.3;
const bbox = [
  CENTER.lat - dLat * pad,
  CENTER.lon - dLon * pad,
  CENTER.lat + dLat * pad,
  CENTER.lon + dLon * pad,
].map((n) => n.toFixed(5)).join(',');

const query = `[out:json][timeout:120];
(
  way["highway"](${bbox});
  way["building"](${bbox});
  way["leisure"~"park|garden|pitch|playground"](${bbox});
  way["landuse"](${bbox});
  way["natural"~"water|wood|scrub"](${bbox});
  way["waterway"~"river|canal|stream"](${bbox});
  way["railway"="rail"](${bbox});
);
out geom;`;

// Public Overpass instances get busy: retry with backoff across mirrors.
const ENDPOINTS = [
  'https://overpass-api.de/api/interpreter',
  'https://overpass.kumi.systems/api/interpreter',
];
async function overpass() {
  for (let attempt = 0; attempt < 6; attempt++) {
    const url = ENDPOINTS[attempt % ENDPOINTS.length];
    try {
      const res = await fetch(url, {
        method: 'POST',
        headers: { 'Content-Type': 'application/x-www-form-urlencoded', 'User-Agent': 'map-render-script' },
        body: new URLSearchParams({ data: query }),
      });
      if (res.ok) return res.json();
      console.warn(`${url} → ${res.status}`);
    } catch (err) {
      console.warn(`${url} → ${err.message}`);
    }
    await new Promise((r) => setTimeout(r, 2000 * 2 ** attempt));
  }
  throw new Error('Overpass unavailable, try again later');
}
const { elements } = await overpass();

const px = ({ lat, lon }) => [
  W / 2 + ((lon - CENTER.lon) * mPerDegLon * W) / WIDTH_M,
  H / 2 - ((lat - CENTER.lat) * mPerDegLat * H) / HEIGHT_M,
];
const path = (geom, close) =>
  geom
    .map((g, i) => {
      const [x, y] = px(g);
      return `${i ? 'L' : 'M'}${x.toFixed(1)} ${y.toFixed(1)}`;
    })
    .join('') + (close ? 'Z' : '');

const MAJOR = /^(motorway|trunk|primary|secondary|tertiary)(_link)?$/;
const MINOR = /^(residential|unclassified|living_street|service|road)$/;
const PATHS = /^(footway|path|cycleway|pedestrian|track|steps)$/;

const GREEN = /^(grass|forest|recreation_ground|orchard|allotments|village_green|cemetery)$/;
const FIELD = /^(farmland|meadow|farmyard|greenfield|brownfield)$/;
const BLOCK = /^(residential|commercial|retail|industrial|construction)$/;

const layers = { field: [], block: [], green: [], water: [], waterLine: [], building: [], major: [], minor: [], small: [], rail: [] };
for (const e of elements) {
  if (!e.geometry || e.geometry.length < 2) continue;
  const t = e.tags ?? {};
  if (t.building) layers.building.push(path(e.geometry, true));
  else if (t.highway && MAJOR.test(t.highway)) layers.major.push(path(e.geometry));
  else if (t.highway && MINOR.test(t.highway)) layers.minor.push(path(e.geometry));
  else if (t.highway && PATHS.test(t.highway)) layers.small.push(path(e.geometry));
  else if (t.railway) layers.rail.push(path(e.geometry));
  else if (t.waterway) layers.waterLine.push(path(e.geometry));
  else if (t.natural === 'water') layers.water.push(path(e.geometry, true));
  else if (t.landuse && BLOCK.test(t.landuse)) layers.block.push(path(e.geometry, true));
  else if (t.landuse && FIELD.test(t.landuse)) layers.field.push(path(e.geometry, true));
  else if (t.leisure || (t.landuse && GREEN.test(t.landuse)) || t.natural) layers.green.push(path(e.geometry, true));
}

const g = (d, attrs) => (d.length ? `<path d="${d.join('')}" ${attrs}/>` : '');
const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${W} ${H}" preserveAspectRatio="xMidYMid slice">
<!-- Map data © OpenStreetMap contributors (ODbL). Generated by scripts/render-map.mjs -->
<rect width="${W}" height="${H}" fill="#f3f0e6"/>
${g(layers.field, 'fill="#efebdf"')}
${g(layers.block, 'fill="#e9e3d2"')}
${g(layers.green, 'fill="#dfe2c8"')}
${g(layers.water, 'fill="#d6dcd6"')}
${g(layers.waterLine, 'fill="none" stroke="#d6dcd6" stroke-width="10" stroke-linecap="round" stroke-linejoin="round"')}
${g(layers.building, 'fill="#e0d8c2" stroke="#d9d0b8" stroke-width="0.6"')}
${g(layers.small, 'fill="none" stroke="#e6dfcc" stroke-width="1.4" stroke-dasharray="3 3"')}
${g(layers.rail, 'fill="none" stroke="#d3c7a6" stroke-width="2.5" stroke-dasharray="10 6"')}
${g(layers.minor, 'fill="none" stroke="#e2d8bd" stroke-width="9" stroke-linecap="round" stroke-linejoin="round"')}
${g(layers.major, 'fill="none" stroke="#ddd0b1" stroke-width="17" stroke-linecap="round" stroke-linejoin="round"')}
${g(layers.minor, 'fill="none" stroke="#ffffff" stroke-width="6.5" stroke-linecap="round" stroke-linejoin="round"')}
${g(layers.major, 'fill="none" stroke="#ffffff" stroke-width="13" stroke-linecap="round" stroke-linejoin="round"')}
</svg>
`;
const out = new URL('../public/map-arad.svg', import.meta.url);
await writeFile(out, svg);
console.log(
  `wrote ${out.pathname} (${(svg.length / 1024).toFixed(0)} KB)`,
  Object.fromEntries(Object.entries(layers).map(([k, v]) => [k, v.length])),
);
